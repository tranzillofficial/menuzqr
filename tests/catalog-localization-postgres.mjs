import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';

const db = new PGlite();
const oldTest = readFileSync(new URL('./catalog-postgres.mjs', import.meta.url), 'utf8');
// Reuse the established import schema, not its test cases.
const setup = oldTest.slice(oldTest.indexOf('await db.exec(`') + 15, oldTest.indexOf('`);'));
await db.exec(setup);
await db.exec(readFileSync(new URL('../supabase/migrations/20261001095745_catalog_import_sections.sql', import.meta.url), 'utf8'));
await db.exec(`
create function public.is_admin() returns boolean language sql as $$select false$$;
alter table catalog_categories add column sort_order integer default 0;
alter table catalog_items add column created_at timestamptz default now(), add column keywords text[] default '{}', add column price_min numeric, add column price_max numeric;
create unique index catalog_categories_name_key on catalog_categories(lower(trim(name)));
alter table catalog_categories enable row level security;
alter table catalog_items enable row level security;
create policy "catalog_categories: read" on catalog_categories for select to authenticated using(is_active);
create policy "catalog: read" on catalog_items for select to authenticated using(is_active);
`);
const restaurant = '20000000-0000-4000-8000-000000000001';
const owner = '10000000-0000-4000-8000-000000000001';
await db.query('insert into restaurants values($1)', [restaurant]);
await db.query("insert into restaurant_members values($1,$2,'owner',true)", [restaurant, owner]);
const oldCategory = (await db.query("insert into catalog_categories(name) values('Sandwiches') returning id")).rows[0].id;
const newCategory = (await db.query("insert into catalog_categories(name) values('الساندوتشات') returning id")).rows[0].id;
const original = (await db.query("insert into catalog_items(name,category_id,suggested_price) values('French Fries',$1,55) returning id", [oldCategory])).rows[0].id;
const duplicate = (await db.query("insert into catalog_items(name,category_id,suggested_price) values('French Fries',$1,60) returning id", [newCategory])).rows[0].id;
await db.query("update catalog_items set created_at='2026-01-01' where id=$1",[original]);
const customCategory = (await db.query("insert into categories(restaurant_id,name,source_catalog_category_id) values($1,'My renamed category',$2) returning id", [restaurant,oldCategory])).rows[0].id;
await db.query("insert into products(restaurant_id,category_id,name,source_catalog_item_id) values($1,$2,'My renamed fries',$3)", [restaurant,customCategory,duplicate]);
const before = (await db.query('select id,name,category_id,source_catalog_item_id from products')).rows;
await db.exec(readFileSync(new URL('../supabase/migrations/20261005083949_catalog_arabic_cleanup_and_menu_languages.sql', import.meta.url), 'utf8'));
await db.exec(readFileSync(new URL('../supabase/migrations/20261005084142_catalog_merge_alias_deletion.sql', import.meta.url), 'utf8'));
assert.deepEqual((await db.query('select id,name,category_id,source_catalog_item_id from products')).rows, before);
assert.equal((await db.query('select count(*) n from catalog_items where merged_into_id is null')).rows[0].n, 1);
const kept = (await db.query('select * from catalog_items where merged_into_id is null')).rows[0];
assert.equal(kept.name, 'بطاطس مقلية');
assert.equal(kept.name_en, 'French Fries');
assert.equal(Number(kept.price_min),55);
assert.equal(Number(kept.price_max),60);
assert.equal((await db.query('select merged_into_id from catalog_categories where id=$1',[oldCategory])).rows[0].merged_into_id,newCategory);
assert.ok([original,duplicate].includes(kept.id));
await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub','${owner}',false)`);
const call = async id => (await db.query('select import_catalog_menu($1,$2,true) result',[restaurant,JSON.stringify([{id,price:75}])])).rows[0].result;
assert.equal((await call(kept.id)).added,0);
assert.equal((await db.query("update catalog_items set name='tampered' returning id")).rows.length,0);
await db.exec('reset role');
const fresh = (await db.query("insert into catalog_items(name,name_en,category_id) values('اختبار','Test',$1) returning id",[newCategory])).rows[0].id;
await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub','${owner}',false)`);
assert.equal((await call(fresh)).sections,0);
assert.equal((await db.query('select name_en from products where source_catalog_item_id=$1',[fresh])).rows[0].name_en,'Test');
assert.equal((await db.query('select count(*) n from categories')).rows[0].n,1);
assert.equal((await db.query("select v.name_en from product_variants v join products p on p.id=v.product_id where p.source_catalog_item_id=$1",[fresh])).rows[0].name_en,'Regular');
await db.exec('reset role');
await db.query('delete from catalog_items where id=$1',[kept.id]);
assert.equal((await db.query('select count(*) n from catalog_items where id in ($1,$2)',[original,duplicate])).rows[0].n,0);
assert.equal((await db.query('select count(*) n from products')).rows[0].n,2);
await db.close();
